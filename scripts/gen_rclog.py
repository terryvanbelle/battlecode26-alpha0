"""Generate java/bots/zdn-teacher/RcLog.java: a RobotController that forwards every call to the real one and reports
each state-changing call to ZT (the teacher recorder) before and after it runs (docs/zdn.md, "Teacher records").

  gen_rclog.py RC_INTERFACE.txt   # the javap listing of battlecode.common.RobotController (engine 1.2.6)
"""
import re, sys
from pathlib import Path

OPS = {   # mutator -> ZT op name (squeak and the indicator calls are handled below)
    'moveForward': 'MOVE_FWD', 'move': 'MOVE', 'turn': 'TURN', 'buildRat': 'BUILD', 'becomeRatKing': 'BECOME_KING',
    'placeDirt': 'PLACE_DIRT', 'removeDirt': 'REMOVE_DIRT', 'placeRatTrap': 'PLACE_RAT_TRAP',
    'removeRatTrap': 'REMOVE_RAT_TRAP', 'placeCatTrap': 'PLACE_CAT_TRAP', 'removeCatTrap': 'REMOVE_CAT_TRAP',
    'pickUpCheese': 'PICKUP', 'attack': 'ATTACK', 'writeSharedArray': 'WRITE', 'transferCheese': 'TRANSFER',
    'throwRat': 'THROW', 'dropRat': 'DROP', 'carryRat': 'CARRY', 'disintegrate': 'DISINTEGRATE', 'resign': 'RESIGN',
    'squeak': 'SQUEAK'}
SHORT = {'battlecode.common.': '', 'java.lang.': ''}


def short(t):
    for k, v in SHORT.items():
        t = t.replace(k, v)
    return t


def main():
    src = Path(sys.argv[1]).read_text()
    out = ['package zdn;', '', 'import battlecode.common.*;', '',
           '/** Generated by scripts/gen_rclog.py. Forwards every call to the engine\'s RobotController; each state-changing',
           ' *  call is reported to ZT.pre before it runs and ZT.post after it returns normally (a call that throws is',
           ' *  never posted). Teacher builds only. */',
           'public final class RcLog implements RobotController {', '    final RobotController rc;', '',
           '    RcLog(RobotController rc) { this.rc = rc; }', '']
    for m in re.finditer(r'public abstract (\S+) (\w+)\(([^)]*)\)( throws [\w.]+)?;', src):
        ret, name, params, throws = short(m.group(1)), m.group(2), m.group(3), m.group(4) or ''
        types = [short(p.strip()) for p in params.split(',')] if params.strip() else []
        args = [f'a{i}' for i in range(len(types))]
        sig = ', '.join(f'{t} {a}' for t, a in zip(types, args))
        call = f'rc.{name}({", ".join(args)})'
        thr = ' throws GameActionException' if throws else ''
        if name in OPS:
            d = next((a for t, a in zip(types, args) if t == 'Direction'), 'null')
            loc = next((a for t, a in zip(types, args) if t == 'MapLocation'), 'null')
            ints = [a for t, a in zip(types, args) if t == 'int']
            i0 = ints[0] if ints else '-1'
            i1 = ints[1] if len(ints) > 1 else '-1'
            pre = f'ZT.pre(ZT.{OPS[name]}, {d}, {loc}, {i0}, {i1});'
            if ret == 'void':
                body = f'{pre} {call}; ZT.post();'
            else:
                body = f'{pre} {ret} r = {call}; if (r) ZT.post(); return r;'
        else:
            body = (f'{call};' if ret == 'void' else f'return {call};')
        out.append(f'    public {ret} {name}({sig}){thr} {{ {body} }}')
    out.append('}')
    dest = Path(__file__).resolve().parent.parent / 'java/bots/zdn-teacher/RcLog.java'
    dest.write_text('\n'.join(out) + '\n')
    print(f'{dest}: {len(out) - 13} methods')


if __name__ == '__main__':
    main()
