"""Pack zdn nets (zdn_train.py's net.json) into java/bots/zdn/ZW.java's layout (read by ZNet.java).

  zdn_pack.py --baby runs/zdn/net-b1/net.json --king runs/zdn/net-k1/net.json --out DIR/ZW.java [--package zdn]
              [--temperature 1.0]

Header chars: 0x5A4E, nS, nL, H1, H, Hh, nC, nK_step, D_step, nR, (nK_r, D_r, nC_r) per register; then every float
as two chars (high half first): W1 [H1][nIn], b1, W2 [H][H1], b2, step scorer (A, a, C, B, E, w, w0), register
scorers (A, a, C if nC_r, B, E, w, w0). Strings are split in chunks so each class-file constant stays under 65535
bytes; chars that a Java unicode escape would turn into source syntax (newline, quote, backslash) are escaped.
"""
import argparse, json, struct
from pathlib import Path


def floats(a):
    import numpy as np
    out = []
    for v in np.asarray(a, dtype=np.float32).ravel():
        b = struct.unpack('>I', struct.pack('>f', float(v)))[0]
        out += [b >> 16, b & 0xFFFF]
    return out


def pack(net):
    import numpy as np
    m = net['meta']
    W1 = np.array(net['W1']); W2 = np.array(net['W2'])
    H1, nIn = W1.shape
    H = W2.shape[0]
    st = net['step']
    Hh = len(st['a'])
    nC = len(st['C'][0]) if 'C' in st else 0
    Bs = np.array(st['B'])
    hdr = [0x5A4E, m['nS'], m['nL'], H1, H, Hh, nC, Bs.shape[0], Bs.shape[2], len(net['regs'])]
    for r in net['regs']:
        B = np.array(r['B'])
        hdr += [B.shape[0], B.shape[2], len(r['C'][0]) if 'C' in r else 0]
    body = floats(W1) + floats(net['b1']) + floats(W2) + floats(net['b2'])

    def scorer(sc, with_c):
        o = floats(sc['A']) + floats(sc['a'])
        if with_c:
            o += floats(sc['C'])
        return o + floats(sc['B']) + floats(sc['E']) + floats(sc['w']) + floats([sc['w0']])

    body += scorer(st, nC > 0)
    for r in net['regs']:
        body += scorer(r, 'C' in r)
    return hdr + body


SAFE = {0x0a: '\\n', 0x0d: '\\r', 0x22: '\\"', 0x5c: '\\\\'}


def java_string(chars, chunk=16000):
    """Chunks of \\uXXXX literals (each char at most 3 bytes in the class file: 16000 * 3 < 65535)."""
    parts = []
    for i in range(0, len(chars), chunk):
        parts.append('"' + ''.join(SAFE.get(c, f'\\u{c:04x}') for c in chars[i:i + chunk]) + '"')
    return parts


def write_zw(out, package, baby=None, king=None, temperature=1.0, version=-1):
    lines = [f'package {package};', '',
             '/** Generated by scripts/zdn_pack.py: packed zdn nets (see ZNet). Empty: no net (options at random). */',
             'final class ZW {']
    for name, path in (('BABY', baby), ('KING', king)):
        if path:
            parts = java_string(pack(json.loads(Path(path).read_text())))
            lines.append(f'    static final String[] {name} = {{')
            lines += [f'        {p},' for p in parts]
            lines.append('    };')
        else:
            lines.append(f'    static final String[] {name} = {{}};')
    lines.append(f'    static final float TEMPERATURE = {temperature}f;')
    lines.append(f'    static final int VERSION = {int(version)};   // the nets\' RL version (records\' trailer); -1: none')
    lines.append('}')
    Path(out).write_text('\n'.join(lines) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--baby')
    ap.add_argument('--king')
    ap.add_argument('--out', required=True)
    ap.add_argument('--package', default='zdn')
    ap.add_argument('--temperature', type=float, default=1.0)
    ap.add_argument('--version', type=int, default=-1)
    a = ap.parse_args()
    write_zw(a.out, a.package, a.baby, a.king, a.temperature, a.version)
    print(f'wrote {a.out}')


if __name__ == '__main__':
    main()
